def capture_edge_fixtures():
    """Capture Edge API store list, Pass 1 relevance search, and Pass 2 pricing.

    Uses a real website JWT for Edge API authentication. Searches for "milk"
    to produce fixtures exercising the two-pass search pipeline.

    Returns:
        store_id: the ID of the first store retrieved (used by mobile fixtures).
    """
    print("\n--- Capturing Edge API Fixtures ---")
    session, token = _get_website_jwt()
    headers = {
        "Authorization": f"Bearer {token}",
        "access_token": token,
        "Content-Type": "application/json",
        "Origin": WEB_BASE,
        "Referer": f"{WEB_BASE}/",
        "User-Agent": "Mozilla/5.0",
    }

    # --- Edge Store List ---
    print("  Fetching Edge store list...")
    r = requests.get(f"{EDGE_BASE}/store", headers=headers, timeout=30)
    r.raise_for_status()
    stores_data = r.json()

    # Validate that the API returned stores. The first store will be used
    # as the context for the subsequent search requests.
    stores = stores_data.get("stores", [])
    if not stores:
        raise RuntimeError("No stores returned from Edge API")
    test_store = stores[0]
    store_id = test_store["id"]
    store_name = test_store["name"]
    region = test_store.get("region", "NI")

    # Save the full store list payload to disk for load_stores tests.
    path = FIXTURE_DIR / "edge_store_list_example.json"
    with open(path, "w", encoding="utf-8") as f:
        json.dump(stores_data, f, indent=2, ensure_ascii=False)
    print(f"    Wrote {path}")

    # Trace metadata so tests can identify which endpoint/store produced this.
    meta_path = FIXTURE_DIR / "edge_store_list_example_meta.json"
    with open(meta_path, "w", encoding="utf-8") as f:
        json.dump({
            "endpoint": f"{EDGE_BASE}/store",
            "store_count": len(stores),
            "first_store_id": store_id,
            "first_store_name": store_name,
            "notes": "Edge API store list captured from live Pak'nSave API."
        }, f, indent=2)
    print(f"    Wrote {meta_path}")

    # Cookies required for Edge search requests (per-store context)
    store_cookies = {
        "eCom_STORE_ID": store_id,
        "STORE_ID_V2": f"{store_id}|False",
        "Region": region,
    }
    search_headers = {
        "Authorization": f"Bearer {token}",
        "access_token": token,
        "Content-Type": "application/json",
        "Origin": WEB_BASE,
        "Referer": f"{WEB_BASE}/shop",
        "User-Agent": "Mozilla/5.0",
    }

    # --- Edge Pass 1: Relevance Search ("milk") ---
    # Passes a query to the Algolia-backed products-index, returning relevance-sorted hits.
    print(f"  Fetching Edge Pass 1 search ('milk') for store {store_name} ({store_id})...")
    p1_payload = {
        "algoliaQuery": {"query": "milk"},
        "page": 0,
        "hitsPerPage": 20,
        "storeId": store_id,
    }
    r1 = requests.post(
        f"{EDGE_BASE}/search/products/query/index/products-index",
        headers=search_headers,
        json=p1_payload,
        cookies=store_cookies,
        timeout=30,
    )
    r1.raise_for_status()
    p1_data = r1.json()

    # Save the Pass 1 response (hits with productID, name, price, categoryTrees).
    path1 = FIXTURE_DIR / "edge_search_pass1_example.json"
    with open(path1, "w", encoding="utf-8") as f:
        json.dump(p1_data, f, indent=2, ensure_ascii=False)
    print(f"    Wrote {path1}")

    with open(FIXTURE_DIR / "edge_search_pass1_meta.json", "w", encoding="utf-8") as f:
        json.dump({
            "endpoint": f"{EDGE_BASE}/search/products/query/index/products-index",
            "store_id": store_id,
            "store_name": store_name,
            "query": "milk",
            "hits_count": len(p1_data.get("hits", [])),
            "notes": "Edge Pass 1 relevance search captured from live API."
        }, f, indent=2)
    print(f"    Wrote {FIXTURE_DIR / 'edge_search_pass1_meta.json'}")

    # Extract productIDs for the Pass 2 filter query
    hits = p1_data.get("hits", [])
    product_ids = [h["productID"] for h in hits[:10]]

    # --- Edge Pass 2: Per-Store Pricing ---
    # Re-queries with Algolia filters on the productIDs and sorts by PRICE_ASC.
    print(f"  Fetching Edge Pass 2 pricing for {len(product_ids)} products...")
    filter_str = " OR ".join(f"productID:{pid}" for pid in product_ids) if product_ids else "productID:none"
    p2_payload = {
        "algoliaQuery": {"query": "milk", "filters": filter_str},
        "page": 0,
        "hitsPerPage": 50,
        "storeId": store_id,
        "sortOrder": "PRICE_ASC",
    }
    r2 = requests.post(
        f"{EDGE_BASE}/search/paginated/products",
        headers=search_headers,
        json=p2_payload,
        cookies=store_cookies,
        timeout=30,
    )
    r2.raise_for_status()
    p2_data = r2.json()

    # Save the Pass 2 response (products with singlePrice/comparativePrice in cents).
    path2 = FIXTURE_DIR / "edge_search_pass2_example.json"
    with open(path2, "w", encoding="utf-8") as f:
        json.dump(p2_data, f, indent=2, ensure_ascii=False)
    print(f"    Wrote {path2}")

    with open(FIXTURE_DIR / "edge_search_pass2_meta.json", "w", encoding="utf-8") as f:
        json.dump({
            "endpoint": f"{EDGE_BASE}/search/paginated/products",
            "store_id": store_id,
            "store_name": store_name,
            "filters": filter_str,
            "products_count": len(p2_data.get("products", [])),
            "notes": "Edge Pass 2 per-store pricing captured from live API."
        }, f, indent=2)
    print(f"    Wrote {FIXTURE_DIR / 'edge_search_pass2_meta.json'}")

    return store_id


