def capture_mobile_fixtures(store_id):
    """Capture Mobile API login, physical stores, and product search responses.

    Uses cloudscraper to bypass anti-bot protection. Searches for "milk"
    to produce a fixture exercising the single-pass Mobile search flow.

    Args:
        store_id: the Edge store ID used for the Mobile search context.
    """
    print("\n--- Capturing Mobile API Fixtures ---")
    scraper = cloudscraper.create_scraper()

    # --- Mobile Guest Login ---
    # A guest POST returns an access_token used for subsequent authenticated requests.
    print("  Fetching Mobile guest login token...")
    r = scraper.post(
        f"{MOBILE_BASE}/mobile/user/login/guest",
        json={"banner": "PNS"},
        headers={"User-Agent": "PAKnSAVEApp/4.32.0", "Content-Type": "application/json"},
    )
    r.raise_for_status()
    login_data = r.json()
    token = login_data["access_token"]

    # Save the login token response (access_token expires after 30 minutes).
    path = FIXTURE_DIR / "mobile_login_example.json"
    with open(path, "w", encoding="utf-8") as f:
        json.dump(login_data, f, indent=2, ensure_ascii=False)
    print(f"    Wrote {path}")

    with open(FIXTURE_DIR / "mobile_login_meta.json", "w", encoding="utf-8") as f:
        json.dump({
            "endpoint": f"{MOBILE_BASE}/mobile/user/login/guest",
            "notes": "Mobile guest token authentication captured from live API."
        }, f, indent=2)
    print(f"    Wrote {FIXTURE_DIR / 'mobile_login_meta.json'}")

    # Auth headers for subsequent Mobile requests
    auth_headers = {
        "Authorization": f"Bearer {token}",
        "access_token": token,
        "User-Agent": "PAKnSAVEApp/4.32.0",
        "Content-Type": "application/json",
    }

    # --- Mobile Physical Stores ---
    print("  Fetching Mobile physical store list...")
    r2 = scraper.get(f"{MOBILE_BASE}/mobile/store/physical", headers=auth_headers, timeout=30)
    r2.raise_for_status()
    stores_data = r2.json()

    path2 = FIXTURE_DIR / "mobile_stores_example.json"
    with open(path2, "w", encoding="utf-8") as f:
        json.dump(stores_data, f, indent=2, ensure_ascii=False)
    print(f"    Wrote {path2}")

    with open(FIXTURE_DIR / "mobile_stores_meta.json", "w", encoding="utf-8") as f:
        json.dump({
            "endpoint": f"{MOBILE_BASE}/mobile/store/physical",
            "store_count": len(stores_data.get("stores", [])),
            "notes": "Mobile store list captured from live API."
        }, f, indent=2)
    print(f"    Wrote {FIXTURE_DIR / 'mobile_stores_meta.json'}")

    # --- Mobile Product Search ("milk") ---
    # Searches for "milk" under the PNS banner for the specified store.
    print(f"  Fetching Mobile product search ('milk') for store {store_id}...")
    r3 = scraper.post(
        f"{MOBILE_BASE}/mobile/ecomm-products/PNS/{store_id}/search?q=milk&hitsPerPage=20",
        headers=auth_headers,
        json=[],
    )
    r3.raise_for_status()
    search_data = r3.json()

    path3 = FIXTURE_DIR / "mobile_search_example.json"
    with open(path3, "w", encoding="utf-8") as f:
        json.dump(search_data, f, indent=2, ensure_ascii=False)
    print(f"    Wrote {path3}")

    with open(FIXTURE_DIR / "mobile_search_meta.json", "w", encoding="utf-8") as f:
        json.dump({
            "endpoint": f"{MOBILE_BASE}/mobile/ecomm-products/PNS/{store_id}/search",
            "store_id": store_id,
            "query": "milk",
            "products_count": len(search_data) if isinstance(search_data, list) else len(search_data.get("products", [])),
            "notes": "Mobile product search response captured from live API."
        }, f, indent=2)
    print(f"    Wrote {FIXTURE_DIR / 'mobile_search_meta.json'}")


