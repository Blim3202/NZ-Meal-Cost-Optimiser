import requests
import cloudscraper
from pathlib import Path

# Fixture directory lives alongside this script
FIXTURE_DIR = Path(__file__).resolve().parent
WEB_BASE = "https://www.paknsave.co.nz"
EDGE_BASE = "https://api-prod.paknsave.co.nz/v1/edge"
MOBILE_BASE = "https://api-prod.prod.fsniwaikato.kiwi/prod"


# ---------------------------------------------------------------------------
# HTTP helpers
# ---------------------------------------------------------------------------
def _get_website_jwt():
    """Get website JWT (fs-user-token) via public website flow.

    Mirrors the authentication used by PaknSaveEdgeAPI.authenticate():
    a POST to /api/user/get-current-user with an established session
    returns a cookie containing the JWT bearer token for Edge API calls.

    Returns:
        session: an authenticated requests.Session
        token: the fs-user-token JWT string
    """
    print("  [Auth] Getting website JWT...")
    session = requests.Session()
    session.headers.update({
        "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36",
        "Origin": WEB_BASE,
        "Referer": WEB_BASE + "/",
    })
    session.get(WEB_BASE, timeout=30)
    r = session.post(f"{WEB_BASE}/api/user/get-current-user", json={}, timeout=30)
    r.raise_for_status()
    token = session.cookies.get("fs-user-token")
    if not token:
        raise RuntimeError("Failed to get fs-user-token cookie")
    return session, token


