def capture_store_finder_fixtures():
    """Capture the store-finder page HTML containing __NEXT_DATA__.

    Extracts the embedded Next.js JSON payload which contains all store
    location data for the website store-finder.
    """
    print("\n--- Capturing Store Finder Fixture ---")
    scraper = cloudscraper.create_scraper()
    headers = {"User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64; rv:136.0) Gecko/20100101 Firefox/136.0"}

    print("  Fetching store-finder page...")
    r = scraper.get(f"{WEB_BASE}/store-finder", headers=headers)
    r.raise_for_status()

    # The __NEXT_DATA__ script tag contains the full Next.js payload including
    # all store locations — no separate API call is needed.
    match = re.search(
        r'<script id="__NEXT_DATA__" type="application/json">(.*?)</script>',
        r.text,
        re.DOTALL,
    )
    if not match:
        raise RuntimeError("Could not find __NEXT_DATA__ in store-finder page")

    next_data = json.loads(match.group(1))

    path = FIXTURE_DIR / "store_finder_page_example.json"
    with open(path, "w", encoding="utf-8") as f:
        json.dump(next_data, f, indent=2, ensure_ascii=False)
    print(f"    Wrote {path}")

    with open(FIXTURE_DIR / "store_finder_meta.json", "w", encoding="utf-8") as f:
        json.dump({
            "endpoint": f"{WEB_BASE}/store-finder",
            "notes": "__NEXT_DATA__ extracted from Pak'nSave store-finder page."
        }, f, indent=2)
    print(f"    Wrote {FIXTURE_DIR / 'store_finder_meta.json'}")


