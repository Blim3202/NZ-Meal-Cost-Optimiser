# Fixture 3: store_data_example.json
# ---------------------------------------------------------------------------
# Captures a real slice of the CDX site-location API response.
#
# Source: GET https://api.cdx.nz/site-location/api/v1/sites
#
# We capture the first 5 sites that have valid coordinates. This gives the
# test suite real coordinate data for haversine distance tests.
# ---------------------------------------------------------------------------


def _capture_store_data_example(raw_store_data, limit=5):
    """Save a slice (first N sites with coords) of the CDX response as a fixture.

    Args:
        raw_store_data: the full CDX JSON response.
        limit: number of sites to keep (must have valid coords).
    """
    # Filter to sites with valid extra1, extra2, lat, lon
    sites = raw_store_data.get("siteDetail", [])
    filtered = []
    for detail in sites:
        site = detail.get("site", {})
        extra1 = site.get("extra1")
        extra2 = site.get("extra2")
        lat = site.get("latitude")
        lon = site.get("longitude")
        if (extra1 and str(extra1) != "null"
                and extra2 and str(extra2) != "null"
                and lat and lon):
            filtered.append(detail)
            if len(filtered) >= limit:
                break

    slice_data = {"siteDetail": filtered}
    path = FIXTURE_DIR / "store_data_example.json"
    with open(path, "w", encoding="utf-8") as f:
        json.dump(slice_data, f, indent=4, ensure_ascii=False)
    print(f"      Saved {len(filtered)} store(s) to {path}")


# ---------------------------------------------------------------------------
# Fixture 4: stores_fixture.csv
# ---------------------------------------------------------------------------
# CSV version of the store data in store_data_example.json, using the same
# 5-column structure that woolworths_setup.fetch_store_data() writes:
#   id (extra1/filfilmentStoreId), name, address, latitude, longitude.
# This is the canonical fixture that tests and woolworths_api.get_nearby_stores()
# read via STORE_CSV.
# ---------------------------------------------------------------------------

def _capture_store_data_csv(raw_store_data, limit=3):
    """Save the first N stores from the CDX response as a CSV matching
    the fetch_store_data() column structure.

    Columns: id (extra1/fulfilmentStoreId), name, address, latitude, longitude
    Output filename: stores_fixture.csv
    """
    sites = raw_store_data.get("siteDetail", [])[:limit]

    rows = []
    for detail in sites:
        site = detail.get("site", {})
        extra1 = site.get("extra1")
        lat = site.get("latitude")
        lon = site.get("longitude")
        # Only include sites with valid extra1 and coordinates
        if extra1 and str(extra1) != "null" and lat and lon:
            rows.append({
                "id": str(extra1),
                "name": site.get("name", ""),
                "address": site.get("addressLine1", ""),
                "latitude": float(lat),
                "longitude": float(lon),
            })

    path = FIXTURE_DIR / "stores_fixture.csv"
    fieldnames = ["id", "name", "address", "latitude", "longitude"]
    with open(path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)
    print(f"[4/5] Wrote {len(rows)} row(s) to {path}")


# ---------------------------------------------------------------------------
# Fixture 6: nearby_stores_example.json
# ---------------------------------------------------------------------------
# Captures a real set of nearby stores for a test address, using haversine
# distance filtering. This exercises get_nearby_stores() with real coords.
# ---------------------------------------------------------------------------

def _capture_nearby_stores_example(raw_store_data):
    """Save metadata for the stores in store_data_example.json so the test
    suite can verify haversine distance calculations.

    Also writes a reference point (the first store's coordinates) that
    tests can use as a query origin.
    """
    sites = raw_store_data.get("siteDetail", [])[:5]
    stores = []
    reference = None

    for i, detail in enumerate(sites):
        site = detail.get("site", {})
        lat = site.get("latitude")
        lon = site.get("longitude")
        if not lat or not lon:
            continue

        entry = {
            "name": site.get("name", ""),
            "pickupAddressId": str(site.get("extra2", "")),
            "fulfilmentStoreId": int(site.get("extra1", 0)),
            "lat": float(lat),
            "lon": float(lon),
        }
        stores.append(entry)
        if i == 0:
            reference = {"lat": float(lat), "lon": float(lon)}

    meta = {"reference_point": reference, "stores": stores}

    path = FIXTURE_DIR / "nearby_stores_example.json"
    with open(path, "w", encoding="utf-8") as f:
        json.dump(meta, f, indent=2, ensure_ascii=False)
    print(f"      Wrote {len(stores)} store(s) + reference point to {path}")


