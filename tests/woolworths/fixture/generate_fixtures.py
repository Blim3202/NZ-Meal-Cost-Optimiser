# 6. shell_example1.json
# ---------------------------------------------------------------------------
# This file captures a real response from the Woolworths shell endpoint:
#   GET /api/v1/shell
#
# The shell endpoint returns the current store context (fulfilmentStoreId,
# method). It is used by set_store_context() to VERIFY that the injected
# cw-lrkswrdjp cookie took effect. If the shell still shows the default
# store (9171), set_store_context() raises RuntimeError.
#
# This fixture captures the shell response for Nelson Junction Woolworths
# (extra1=9290) Nelson Junction Woolworths, after the cw-lrkswrdjp cookie has been injected.
# ---------------------------------------------------------------------------

def _capture_shell_example(test_store):
    """Capture a real /api/v1/shell response for the given store.

    The session is freshly created, seeded via GET /, and the cw-lrkswrdjp
    cookie is injected before calling /api/v1/shell. The response is saved
    as shell_example1.json.


    Args:
        test_store: dict with 'name', 'extra1', 'extra2' from CDX data.
    """
    session = _create_session()
    _inject_store_context(session, test_store["extra1"])

    resp = session.get(f"{BASE_URL}/shell", timeout=15)
    resp.raise_for_status()
    shell_data = resp.json()

    # Save the full shell response
    path = FIXTURE_DIR / "shell_example1.json"
    with open(path, "w", encoding="utf-8") as f:
        json.dump(shell_data, f, indent=2, ensure_ascii=False)
    print(f"      Wrote {path}")


